package edu.course.lab02;

/**
 * Статус жизненного цикла образца данных в машинном обучении.
 */
public enum SampleStatus {
    /** Сырые данные, только что полученные из источника. */
    RAW,

    /** Данные прошли предварительную обработку/очистку. */
    PROCESSED,

    /** Данные полностью готовы для подачи в модель обучения. */
    READY
}
